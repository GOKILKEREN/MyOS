import sys, os

print('/* AUTO-GENERATED by gen_embed.py. Do not edit. */')
print('#include "user_programs.h"')

files = []
for path in sys.argv[1:]:
    name = os.path.basename(path)
    if name.endswith('.elf'): name = name[:-4]
    name = name.upper() + '.ELF'
    var = 'prog_' + name.replace('.', '_').lower()
    data = open(path, 'rb').read()
    print()
    print('static const unsigned char %s[] = {' % var)
    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        print('    ' + ','.join('0x%02x' % b for b in chunk) + ',')
    print('};')
    files.append((name, var, len(data)))

print()
print('const user_prog_t user_programs[] = {')
for name, var, size in files:
    print('    { "%s", %s, %d },' % (name, var, size))
print('};')
print('const unsigned int user_program_count = %d;' % len(files))
